
-- =========================================================
-- StockFlow - 01_schema.sql
-- PostgreSQL 18
-- Descripcion: esquema relacional del sistema de inventario
-- =========================================================

BEGIN;

-- ---------------------------------------------------------
-- 1. Usuarios del sistema
-- ---------------------------------------------------------
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL
);

-- ---------------------------------------------------------
-- 2. Catalogo de productos
-- ---------------------------------------------------------
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    unit_price NUMERIC(12, 2) NOT NULL
        CHECK (unit_price >= 0),
    stock INTEGER NOT NULL DEFAULT 0
        CHECK (stock >= 0)
);

-- ---------------------------------------------------------
-- 3. Historial de movimientos de inventario
-- ---------------------------------------------------------
CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    movement_type VARCHAR(3) NOT NULL
        CHECK (movement_type IN ('IN', 'OUT')),

    quantity INTEGER NOT NULL
        CHECK (quantity > 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inventory_movements_product
        FOREIGN KEY (product_id)
        REFERENCES products (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_inventory_movements_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE RESTRICT
);

-- ---------------------------------------------------------
-- 4. Indices para consultar el historial
-- ---------------------------------------------------------
CREATE INDEX ix_inventory_movements_product_date
    ON inventory_movements (product_id, created_at DESC);

CREATE INDEX ix_inventory_movements_user_date
    ON inventory_movements (user_id, created_at DESC);

COMMIT;
